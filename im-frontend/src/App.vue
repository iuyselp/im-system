<template>
  <router-view />
</template>

<script setup>
import { onMounted } from 'vue'
import { useUserStore } from '@/store/user'

const userStore = useUserStore()

onMounted(() => {
  // 检查本地存储的 Token
  const token = localStorage.getItem('token')
  if (token) {
    userStore.setToken(token)
    // 获取用户信息
    userStore.getUserInfo()
  }
})
</script>

